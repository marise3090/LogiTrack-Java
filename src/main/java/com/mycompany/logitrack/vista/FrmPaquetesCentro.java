    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
            if (centroSeleccionado == null) {
        return;
    }

    ListaDoblePaquetes lista =
            centroSeleccionado.getListaPaquetes();

    Paquete paquete = lista.obtenerActual();

    if (paquete == null) {

        JOptionPane.showMessageDialog(
                this,
                "No hay ningún paquete para eliminar.",
                "Lista vacía",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea eliminar el paquete "
            + paquete.getId() + "?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta != JOptionPane.YES_OPTION) {
        return;
    }

    lista.eliminarActual();

    actualizarFormulario();

    JOptionPane.showMessageDialog(
            this,
            "Paquete eliminado correctamente.",
            "Eliminación exitosa",
            JOptionPane.INFORMATION_MESSAGE
    );
        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed


    private void txtIdPaqueteActionPerformed(java.awt.event.ActionEvent evt) {
        if (centroSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Primero seleccione un centro.",
                    "No hay centro", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int id = Integer.parseInt(txtIdPaquete.getText().trim());
            Paquete encontrado = centroSeleccionado.getListaPaquetes().buscarRecursivo(id);

            if (encontrado == null) {
                JOptionPane.showMessageDialog(this,
                        "No existe un paquete con el ID " + id + " en este centro.",
                        "Búsqueda recursiva", JOptionPane.INFORMATION_MESSAGE);
                return;
            }

            actualizarFormulario();
            JOptionPane.showMessageDialog(this,
                    "Paquete encontrado mediante búsqueda recursiva.",
                    "Búsqueda recursiva", JOptionPane.INFORMATION_MESSAGE);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Digite un ID numérico y presione Enter para buscar.",
                    "ID inválido", JOptionPane.ERROR_MESSAGE);
        }
    }

