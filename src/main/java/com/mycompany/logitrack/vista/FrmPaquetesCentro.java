    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
         if (centroSeleccionado == null) {

        JOptionPane.showMessageDialog(
                this,
                "Primero debe registrar un centro de distribución.",
                "No hay centros",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    if (txtIdPaquete.getText().trim().isEmpty()
        || txtDescripcion.getText().trim().isEmpty()
        || txtDestino.getText().trim().isEmpty()
        || txtEstado.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Todos los campos son obligatorios.",
                "Datos incompletos",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        int id = Integer.parseInt(
                txtIdPaquete.getText().trim()
        );

        ListaDoblePaquetes lista =
                centroSeleccionado.getListaPaquetes();

        if (lista.buscarRecursivo(id) != null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ya existe un paquete con el ID " + id
                    + " en este centro.",
                    "ID duplicado",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        Paquete paquete = new Paquete(
        id,
        txtDescripcion.getText().trim(),
        txtDestino.getText().trim(),
        txtEstado.getText().trim()
);

        lista.agregar(paquete);

        lista.irAlInicio();

        while (lista.siguiente() != null) {
            // Avanza hasta el último paquete.
        }

        actualizarFormulario();

        JOptionPane.showMessageDialog(
                this,
                "Paquete agregado correctamente.",
                "Registro exitoso",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (NumberFormatException ex) {

        JOptionPane.showMessageDialog(
                this,
                "El ID debe contener solamente números enteros.",
                "ID inválido",
                JOptionPane.ERROR_MESSAGE
        );
    }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnAgregarActionPerformed

