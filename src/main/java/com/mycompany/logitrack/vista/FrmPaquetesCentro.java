    private void cargarCentros() {

    cboCentros.removeAllItems();

    for (CentroDistribucion centro : listaCentros.obtenerCentros()) {
        cboCentros.addItem(centro);
    }

    if (cboCentros.getItemCount() > 0) {
        cboCentros.setSelectedIndex(0);
        centroSeleccionado =
                (CentroDistribucion) cboCentros.getSelectedItem();
    } else {
        centroSeleccionado = null;
    }
}
    
    private void limpiarCampos() {
    txtIdPaquete.setText("");
    txtDescripcion.setText("");
    txtDestino.setText("");
    txtEstado.setText("");
}
    
    private void actualizarFormulario() {

    if (centroSeleccionado == null) {
        limpiarCampos();
        lblPosicion.setText("Paquete: 0 de 0");
        return;
    }

    ListaDoblePaquetes lista =
            centroSeleccionado.getListaPaquetes();

    Paquete paquete = lista.obtenerActual();

    if (paquete == null) {
        limpiarCampos();
        lblPosicion.setText("Paquete: 0 de 0");
        return;
    }

    txtIdPaquete.setText(
            String.valueOf(paquete.getId())
    );

    txtDescripcion.setText(
        paquete.getDescripcion()
);

    txtDestino.setText(
            paquete.getDestino()
    );

    txtEstado.setText(
            paquete.getEstado()
    );

    actualizarPosicion();
}
    
    private void actualizarPosicion() {

    if (centroSeleccionado == null) {
        lblPosicion.setText("Paquete: 0 de 0");
        return;
    }

    ListaDoblePaquetes lista =
            centroSeleccionado.getListaPaquetes();

    Paquete actual = lista.obtenerActual();

    if (actual == null) {
        lblPosicion.setText("Paquete: 0 de 0");
        return;
    }

    int posicion = 0;
    int contador = 1;

    for (Paquete paquete : lista.obtenerPaquetes()) {

        if (paquete == actual) {
            posicion = contador;
            break;
        }

        contador++;
    }

    lblPosicion.setText(
            "Paquete: " + posicion
            + " de " + lista.obtenerCantidad()
    );
}
    
    

