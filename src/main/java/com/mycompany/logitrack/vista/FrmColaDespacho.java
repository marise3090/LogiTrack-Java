    private void actualizarTabla() {

    modeloTabla.setRowCount(0);

    for (Paquete paquete : cola.obtenerPaquetes()) {

        modeloTabla.addRow(new Object[]{
            paquete.getId(),
            paquete.getDescripcion(),
            paquete.getDestino(),
            paquete.getEstado()
        });
    }
    
    
}
    private boolean existePaquete(int id) {

    for (Paquete paquete : cola.obtenerPaquetes()) {

        if (paquete.getId() == id) {
            return true;
        }
    }

    return false;
}

