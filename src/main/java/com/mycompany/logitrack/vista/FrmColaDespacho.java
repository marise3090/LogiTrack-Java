    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
    if (cola.estaVacia()) {

        JOptionPane.showMessageDialog(
                this,
                "No hay paquetes pendientes en la cola.",
                "Cola vacía",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    Paquete paquete = cola.desencolar();
    paquete.setEstado("EN_TRANSITO");
    Entrega entrega = new Entrega(
        paquete.getId(),
        "Transportista",
        java.time.LocalDate.now().toString(),
        "ENTREGADO"
);

historial.apilar(entrega);

    JOptionPane.showMessageDialog(
            this,
            "Paquete despachado correctamente.\n\n"
            + "ID: " + paquete.getId()
            + "\nDescripción: " + paquete.getDescripcion()
            + "\nDestino: " + paquete.getDestino()
            + "\nEstado: " + paquete.getEstado(),
            "Despacho realizado",
            JOptionPane.INFORMATION_MESSAGE
    );

    actualizarTabla();


        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        
    try {

        String idTexto = JOptionPane.showInputDialog(
                this,
                "Ingrese el ID del paquete:",
                "Registrar paquete",
                JOptionPane.QUESTION_MESSAGE
        );

        if (idTexto == null) {
            return;
        }

        idTexto = idTexto.trim();

        if (idTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "El ID es obligatorio.",
                    "Dato inválido",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int id = Integer.parseInt(idTexto);

        if (id <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "El ID debe ser mayor que cero.",
                    "Dato inválido",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (existePaquete(id)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ya existe un paquete con el ID " + id + ".",
                    "ID duplicado",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String descripcion = JOptionPane.showInputDialog(
                this,
                "Ingrese la descripción del paquete:",
                "Registrar paquete",
                JOptionPane.QUESTION_MESSAGE
        );

        if (descripcion == null) {
            return;
        }

        descripcion = descripcion.trim();

        if (descripcion.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "La descripción es obligatoria.",
                    "Dato inválido",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String destino = JOptionPane.showInputDialog(
                this,
                "Ingrese el destino del paquete:",
                "Registrar paquete",
                JOptionPane.QUESTION_MESSAGE
        );

        if (destino == null) {
            return;
        }

        destino = destino.trim();

        if (destino.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "El destino es obligatorio.",
                    "Dato inválido",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Paquete nuevoPaquete = new Paquete(
                id,
                descripcion,
                destino,
                "REGISTRADO"
        );

        cola.encolar(nuevoPaquete);

        actualizarTabla();

        JOptionPane.showMessageDialog(
                this,
                "Paquete registrado correctamente.\n"
                + "Posición en la cola: "
                + cola.obtenerCantidad(),
                "Registro exitoso",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (NumberFormatException ex) {

        JOptionPane.showMessageDialog(
                this,
                "El ID debe contener solamente números enteros.",
                "ID inválido",
                JOptionPane.ERROR_MESSAGE
        );
    }
    
    
        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

